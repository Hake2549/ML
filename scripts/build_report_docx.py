def normalized_template(src):
    """เทมเพลตมีค่าระยะขอบเป็นทศนิยม (เช่น 1440.0000000000002) ซึ่ง python-docx อ่านไม่ได้
    จึงทำสำเนาที่ปัดค่าเหล่านี้เป็นจำนวนเต็มก่อนเปิดใช้งาน"""
    import re, shutil, tempfile, zipfile
    out = Path(tempfile.gettempdir()) / 'report_template_fixed.docx'
    with zipfile.ZipFile(src) as zin, zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED) as zout:
        for item in zin.infolist():
            data = zin.read(item.filename)
            if item.filename.endswith('.xml'):
                text = data.decode('utf-8')
                text = re.sub(r'(\s[\w:]+)="(-?\d+)\.\d+"',
                              lambda m: m.group(0) if m.group(1).strip().endswith('version')
                              else f'{m.group(1)}="{m.group(2)}"', text)
                data = text.encode('utf-8')
            zout.writestr(item, data)
    return out


