def style_run(run, size=BODY, bold=False, italic=False, color=None):
    run.font.name = FONT
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    if color is not None:
        run.font.color.rgb = color
    rPr = run._r.get_or_add_rPr()
    rFonts = rPr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = rPr.makeelement(qn('w:rFonts'), {})
        rPr.insert(0, rFonts)
    for attr in ('w:ascii', 'w:hAnsi', 'w:cs'):      # w:cs = ฟอนต์สำหรับภาษาไทย
        rFonts.set(qn(attr), FONT)
    return run


def new_par(text='', size=BODY, bold=False, italic=False, align=None, indent=0.0,
            space_after=6, color=None):
    p = doc.add_paragraph()
    p.style = doc.styles['normal']
    if align is not None:
        p.alignment = align
    pf = p.paragraph_format
    pf.space_after = Pt(space_after)
    pf.space_before = Pt(0)
    if indent:
        pf.left_indent = Inches(indent)
        pf.first_line_indent = Inches(-0.22)
    if text:
        style_run(p.add_run(text), size, bold, italic, color)
    return p


def rich_par(parts, **kw):
    """parts = [(text, bold), ...] สำหรับย่อหน้าที่มีตัวหนาแทรก"""
    p = new_par('', **kw)
    for t, b in parts:
        style_run(p.add_run(t), kw.get('size', BODY), b)
    return p


def set_borders(table):
    tbl = table._tbl
    tblPr = tbl.tblPr
    borders = tblPr.makeelement(qn('w:tblBorders'), {})
    for edge in ('top', 'left', 'bottom', 'right', 'insideH', 'insideV'):
        el = borders.makeelement(qn(f'w:{edge}'), {})
        el.set(qn('w:val'), 'single')
        el.set(qn('w:sz'), '6')
        el.set(qn('w:color'), '7F7F7F')
        borders.append(el)
    tblPr.append(borders)


def shade_header(table):
    for cell in table.rows[0].cells:
        tcPr = cell._tc.get_or_add_tcPr()
        shd = tcPr.makeelement(qn('w:shd'), {})
        shd.set(qn('w:val'), 'clear')
        shd.set(qn('w:fill'), 'E8EDF2')
        tcPr.append(shd)


def make_table(headers, rows, widths, caption=None):
    tab_no[0] += 1
    t = doc.add_table(rows=len(rows) + 1, cols=len(headers))
    t.autofit = False
    set_borders(t)          # เทมเพลตไม่มีสไตล์ Table Grid จึงวาดเส้นขอบเอง
    shade_header(t)
    for ci, (h, w) in enumerate(zip(headers, widths)):
        cell = t.cell(0, ci)
        cell.width = Inches(w)
        style_run(cell.paragraphs[0].add_run(h), BODY - 1, bold=True)
    for ri, row in enumerate(rows, start=1):
        for ci, val in enumerate(row):
            cell = t.cell(ri, ci)
            cell.width = Inches(widths[ci])
            txt = val if isinstance(val, str) else val[0]
            bold = (not isinstance(val, str)) and val[1]
            style_run(cell.paragraphs[0].add_run(txt), BODY - 1, bold=bold)
    cap = new_par(f'ตารางที่ {tab_no[0]}  {caption}' if caption else '', size=BODY - 2,
                  italic=True, align=WD_ALIGN_PARAGRAPH.CENTER, space_after=10)
    return t, cap


def make_figure(name, caption, width=5.8):
    fig_no[0] += 1
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_after = Pt(2)
    p.add_run().add_picture(str(FIG / name), width=Inches(width))
    cap = new_par(f'รูปที่ {fig_no[0]}  {caption}', size=BODY - 2, italic=True,
                  align=WD_ALIGN_PARAGRAPH.CENTER, space_after=10)
    return p, cap


