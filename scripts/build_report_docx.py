# ---------------------------------------------------------------- ประกอบร่าง
def insert_blocks(anchor_p, blocks):
    cursor = anchor_p._p
    for block in blocks:
        kind = block[0]
        if kind == 'p':
            el = new_par(block[1], space_after=8)._p
            cursor.addnext(el); cursor = el
        elif kind == 'rp':
            el = rich_par(block[1], space_after=8)._p
            cursor.addnext(el); cursor = el
        elif kind == 'bl':
            for item in block[1]:
                el = new_par('•  ' + item, indent=0.35, space_after=4)._p
                cursor.addnext(el); cursor = el
        elif kind == 'tb':
            _, headers, rows, widths, caption = block
            t, cap = make_table(headers, rows, widths, caption)
            cursor.addnext(cap._p); cursor.addnext(t._tbl)
            cursor = cap._p
        elif kind == 'fig':
            _, name, caption, width = block
            pic, cap = make_figure(name, caption, width)
            cursor.addnext(cap._p); cursor.addnext(pic._p)
            cursor = cap._p
    return cursor


